"""Refresh the self-hosted fonts in src/assets/fonts.

Run after adding or renaming icons:  python scripts/update-fonts.py   (needs internet once; the app itself never does)

- Inter and Playfair Display: latin + latin-ext subsets (covers English, French, Kinyarwanda and Kiswahili).
- Material Symbols Rounded: only the icons the app uses. Every snake_case string in src/ that is a real
  Material Symbols name is kept, so new icons are picked up automatically.
"""
import glob, hashlib, os, re, time, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "assets", "fonts")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
TEXT_FONTS = "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Playfair+Display:ital,wght@0,500;0,600;0,700;1,500&display=swap"
ICON_FONT = "https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@20..48,400,0..1,0&display=block&icon_names="
ICON_LIST = "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL,GRAD,opsz,wght%5D.codepoints"


def get(url, binary=False):
    for attempt in range(5):  # retry dropped connections
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
                data = r.read()
            return data if binary else data.decode("utf-8")
        except OSError:
            if attempt == 4:
                raise
            time.sleep(2 * (attempt + 1))


def used_icons():
    valid = {line.split()[0] for line in get(ICON_LIST).splitlines() if line.strip()}
    found = set()
    for f in glob.glob(os.path.join(ROOT, "src", "**", "*.js*"), recursive=True):
        found |= set(re.findall(r"[\"'`]([a-z][a-z0-9_]{1,48})[\"'`]", open(f, encoding="utf-8").read()))
    return sorted(found & valid)


def main():
    os.makedirs(OUT, exist_ok=True)
    icons = used_icons()
    sheets = [(get(TEXT_FONTS), {"latin", "latin-ext"}), (get(ICON_FONT + ",".join(icons)), None)]
    rules, saved, files = [], {}, {}  # saved: content hash -> file name, so identical files are stored once
    for css, keep in sheets:
        for subset, block in re.findall(r"(?:/\* ([\w-]+) \*/\s*)?(@font-face \{.*?\})", css, re.S):
            if keep and subset not in keep:
                continue
            family = re.search(r"font-family: '([^']+)'", block).group(1)
            italic = "font-style: italic" in block
            url = re.search(r"url\((https://[^)]+)\)", block).group(1)
            data = get(url, binary=True)
            digest = hashlib.md5(data).hexdigest()
            if digest not in saved:
                base = "material-symbols-rounded" if "Symbols" in family else family.split()[0].lower() + ("-italic" if italic else "")
                saved[digest] = f"{base}-{subset}.woff2" if subset else f"{base}.woff2"
                files[saved[digest]] = data
            rules.append(block.replace(url, "./" + saved[digest]))
    # Google writes one rule per weight even when they share a variable font file. Merge those into one rule with a
    # weight range, so the single-file build embeds each file once.
    merged = {}
    for block in rules:
        key = re.search(r"url\(([^)]+)\)", block).group(1)
        weights = [int(w) for w in re.search(r"font-weight: ([\d ]+);", block).group(1).split()]
        if key in merged:
            merged[key][1].extend(weights)
        else:
            merged[key] = [block, weights]
    rules = [re.sub(r"font-weight: [\d ]+;", f"font-weight: {min(w)} {max(w)};" if min(w) != max(w) else f"font-weight: {w[0]};", block)
             for block, w in merged.values()]
    # Everything downloaded: only now replace the old files, so a failed run never leaves the app without fonts.
    for f in os.listdir(OUT):
        if f.endswith(".woff2"):
            os.remove(os.path.join(OUT, f))
    for name, data in files.items():
        open(os.path.join(OUT, name), "wb").write(data)
    header = "/* Self-hosted fonts, generated by scripts/update-fonts.py. Inter + Playfair Display (latin, latin-ext); Material Symbols Rounded with only the icons the app uses. */"
    open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8").write(header + "\n" + "\n".join(rules) + "\n")
    size = sum(os.path.getsize(os.path.join(OUT, f)) for f in saved.values())
    print(f"{len(icons)} icons, {len(saved)} font files, {size // 1024} KB")


if __name__ == "__main__":
    main()
